    public static EraeColor toColor(final double r, final double g, final double b) {
        final int colorIndex = rgbToIndex(r, g, b);
        return new EraeColor(colorIndex);
    }
    
    public static int rgbToIndex(final double red, final double green, final double blue) {
        int closestIndex = -1;
        double minDistance = Double.MAX_VALUE;
        
        if (red == green && green == blue) {
            for (int i = 0; i < 128; i++) {
                final ColorMatch c = COLOR_SEQ.get(i);
                if (c.isGrayTone()) {
                    final double distance = c.colorDistance(red, green, blue);
                    if (distance < minDistance) {
                        minDistance = distance;
                        closestIndex = i;
                    }
                }
            }
        } else {
            for (int i = 0; i < 0x32; i++) {
                final ColorMatch c = COLOR_SEQ.get(i);
                final double distance = c.colorDistance(red, green, blue);
                
                if (distance < minDistance) {
                    minDistance = distance;
                    closestIndex = i;
                }
            }
        }
        
        final ColorMatch colorMatch = COLOR_SEQ.get(closestIndex);
        //        Erae2ControllerExtension.println(
        //            "MATCH %02X  = %02X %02X %02X   %02X %02X %02X", closestIndex, colorMatch.red, colorMatch.green,
        //            colorMatch.blue, (int) Math.round(red * 255), (int) Math.round(green * 255), (int) Math.round
        //            (blue * 255));
        return colorMatch.index();
    }
